#!/bin/sh
# Speaker PA on/off pop variants: A plain, B soft start, C soft start + reset
# pulse, D driver soft enable, E class D. Letter on the console.
A=/sys/kernel/debug/sprd-adi
rd() { echo $1 > $A/address; cat $A/value; }
wr() { echo $1 > $A/address; echo $2 > $A/value; }
st() { v=$(rd $1); wr $1 $(printf 0x%x $(( (v & ~$2) | $3 ))); }
show() { msg="VARIANTE $1"; echo "$msg" > /dev/kmsg; printf "\n\n   >>> %s <<<\n" "$msg" > /dev/tty0; echo "$(date +%T) $msg CDC4=$(rd 0x62c) CDC2=$(rd 0x624)"; }
paonoff() { st 0x600 0x2000 0x2000; sleep 4; st 0x600 0x2000 0; sleep 4; }
/tmp/pmic-wdg.sh arm 150
printf "\033[2J\033[H   VARIANTEN-TEST startet in 15 s\n" > /dev/tty0
# path up to the PA, silent in the step test
st 0x61c 0x900 0x900; st 0x624 0xc000 0xc000; st 0x68c 0xa00 0xa00
st 0x624 0x10 0x10; st 0x600 0x8000 0x8000
st 0x60c 0x3800 0; st 0x614 0xe000 0x6000; st 0x62c 0x8000 0; wr 0x618 0x400
st 0x624 0x2c00 0x2c00; st 0x62c 0x1000 0x1000; st 0x618 0xc000 0; st 0x600 0x4000 0
st 0x62c 0x6000 0x6000
sleep 15
show "A: wie bisher"; paonoff
st 0x62c 0x3fc 0x2fc
show "B: PA-Soft-Start"; paonoff
st 0x62c 0x100 0x100; st 0x62c 0x100 0
show "C: Soft-Start + Reset-Puls"; st 0x62c 0x100 0x100; st 0x62c 0x100 0; paonoff
st 0x62c 0x3fc 0; st 0x624 0x200 0x200
show "D: DRV_SOFT_EN"; paonoff
st 0x624 0x200 0; st 0x62c 0x8000 0x8000
show "E: Class D"; paonoff
st 0x62c 0x8000 0
st 0x600 0x8000 0; st 0x624 0x10 0; st 0x624 0xc000 0; st 0x68c 0xa00 0; st 0x61c 0x900 0
printf "\n   ENDE\n" > /dev/tty0
/tmp/pmic-wdg.sh disarm
